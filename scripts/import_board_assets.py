"""Validate board exports and compile deterministic palette meshes into Rust."""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KEYS = ("ferrite", "mono", "graphite", "slate", "concrete", "harbor",
        "cyanotype", "phosphor", "verdigris", "bruise")
WIDTH, HEIGHT = 244 * 1.35, 380 * 1.18
MAX_TRIANGLES = 4000


def validate(data):
    if data.get("version") != 1 or data.get("coordinates") != "ricochet-world":
        raise ValueError("Expected version 1 ricochet-world coordinates")
    if data.get("board") not in KEYS:
        raise ValueError("Unknown board key")
    objects = data.get("objects")
    if not isinstance(objects, list) or not objects:
        raise ValueError("Export needs at least one mesh")
    count, names = 0, set()
    for obj in objects:
        name = obj.get("name")
        if not isinstance(name, str) or not name or name in names:
            raise ValueError("Mesh names must be nonempty and unique")
        names.add(name)
        role, ink = obj.get("role"), obj.get("ink")
        if role not in ("artwork", "scenery") or type(ink) is not int or not 0 <= ink <= 12:
            raise ValueError(f"{name}: invalid role or palette ink")
        vertices, triangles = obj.get("vertices"), obj.get("triangles")
        if not isinstance(vertices, list) or not isinstance(triangles, list) or not triangles:
            raise ValueError(f"{name}: missing geometry")
        for v in vertices:
            if not isinstance(v, list) or len(v) != 3 or any(
                    type(n) not in (float, int) or not math.isfinite(n) for n in v):
                raise ValueError(f"{name}: invalid vertex")
            x, y, z = v
            if not (-8 <= x <= WIDTH + 8 and -13 <= y <= HEIGHT + 13 and -24 <= z <= 64):
                raise ValueError(f"{name}: vertex outside cabinet camera envelope")
            if role == "artwork" and not 0.05 <= z <= 0.4:
                raise ValueError(f"{name}: artwork must be flush (z 0.05..0.4)")
        for t in triangles:
            if not isinstance(t, list) or len(t) != 3 or any(
                    type(i) is not int or not 0 <= i < len(vertices) for i in t):
                raise ValueError(f"{name}: invalid triangle indices")
            a, b, c = [vertices[i] for i in t]
            u, v = [b[i] - a[i] for i in range(3)], [c[i] - a[i] for i in range(3)]
            cross = [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]]
            if sum(n*n for n in cross) < 1e-10:
                raise ValueError(f"{name}: degenerate triangle")
            # Require the entire triangle to lie in one safe half-plane.
            # Checking individual vertices alone allows triangles across the field.
            if role == "scenery" and not (all(p[1] < 22 * 1.18 - 4 for p in (a,b,c))
                    or all(p[0] < 22 * 1.35 - 4 for p in (a,b,c))
                    or all(p[0] > 221 * 1.35 + 4 for p in (a,b,c))):
                raise ValueError(f"{name}: scenery overlaps playable area")
        count += len(triangles)
    if count > MAX_TRIANGLES:
        raise ValueError(f"Triangle budget exceeded: {count} > {MAX_TRIANGLES}")
    return count


def compile_assets(source):
    boards, receipts = {}, []
    for path in sorted(source.glob("*.json")):
        raw = path.read_bytes()
        data = json.loads(raw)
        count = validate(data)
        key = data["board"]
        if key in boards:
            raise ValueError(f"Duplicate board {key}")
        boards[key] = data
        receipts.append(dict(file=path.name, board=key, triangles=count,
                             sha256=hashlib.sha256(raw).hexdigest()))
    if not boards:
        return ("// Generated by scripts/import_board_assets.py. Do not edit.\n"
                "use super::Face;\n"
                "pub fn append(_out: &mut Vec<Face>, _key: &str) {}\n"), receipts
    lines = ["// Generated by scripts/import_board_assets.py. Do not edit.",
             "use super::{Face, P3};", "pub fn append(out: &mut Vec<Face>, key: &str) {",
             "    match key {"]
    for key, data in sorted(boards.items()):
        lines.append(f'        "{key}" => {{')
        for obj in data["objects"]:
            for triangle in obj["triangles"]:
                points = ", ".join("P3::new(" + ", ".join(f"{n:.9e}f32" for n in obj["vertices"][i]) + ")" for i in triangle)
                floor = "true" if obj["role"] == "artwork" else "false"
                lines.append(f"            out.push(Face {{ points: vec![{points}], ink: {obj['ink']}, floor: {floor} }});")
        lines.append("        }")
    lines += ["        _ => {}", "    }", "}", ""]
    return "\n".join(lines), receipts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "assets/boards")
    parser.add_argument("--check", action="store_true", help="Validate without writing")
    args = parser.parse_args()
    if not args.source.is_dir():
        parser.error(f"Missing source directory: {args.source}")
    code, receipts = compile_assets(args.source)
    if not args.check:
        (ROOT / "src/board_assets.rs").write_text(code, encoding="utf-8")
        (ROOT / "assets/boards/receipt.json.txt").write_text(
            json.dumps(receipts, indent=2) + "\n", encoding="utf-8")
    print(f"Validated {len(receipts)} boards, {sum(r['triangles'] for r in receipts)} triangles")


if __name__ == "__main__":
    main()
